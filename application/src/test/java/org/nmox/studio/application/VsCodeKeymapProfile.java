    /** The text between two markers of the ui layer, the markers' own lines included. */
    static String region(String layer, String begin, String end) {
        int b = layer.indexOf(begin);
        int e = layer.indexOf(end);
        if (b < 0 || e < b) {
            throw new IllegalStateException("the ui layer has no " + begin + " ... " + end + " region");
        }
        int lineStart = layer.lastIndexOf('\n', b) + 1;
        int lineEnd = layer.indexOf('\n', e);
        return layer.substring(lineStart, lineEnd < 0 ? layer.length() : lineEnd + 1);
    }

    /** What is on disk now, in the shape of an {@link Output}; line endings folded so a CRLF checkout compares equal. */
    static Output committed() throws IOException {
        String layer = read(UI_LAYER);
        Map<String, String> files = new TreeMap<>();
        Path dir = UI_RESOURCES.resolve(FILES_DIR);
        if (Files.isDirectory(dir)) {
            try (Stream<Path> s = Files.list(dir)) {
                for (Path p : s.filter(p -> p.getFileName().toString().endsWith(".xml")).sorted().toList()) {
                    files.put(p.getFileName().toString(), read(p));
                }
            }
        }
        return new Output(region(layer, GLOBAL_BEGIN, GLOBAL_END), region(layer, EDITORS_BEGIN, EDITORS_END), files,
                Files.exists(DISPLACED) ? read(DISPLACED) : "");
    }

    private static String read(Path p) throws IOException {
        return Files.readString(p, StandardCharsets.UTF_8).replace("\r\n", "\n");
    }

    /** Writes what was generated over what is committed; a keybinding file no longer generated is deleted. */
    static void write(Output out) throws IOException {
        String layer = read(UI_LAYER);
        layer = layer.replace(region(layer, GLOBAL_BEGIN, GLOBAL_END), out.globalRegion());
        layer = layer.replace(region(layer, EDITORS_BEGIN, EDITORS_END), out.editorsRegion());
        Files.writeString(UI_LAYER, layer, StandardCharsets.UTF_8);
        Path dir = UI_RESOURCES.resolve(FILES_DIR);
        Files.createDirectories(dir);
        try (Stream<Path> s = Files.list(dir)) {
            for (Path p : s.filter(p -> p.getFileName().toString().endsWith(".xml")).toList()) {
                if (!out.files().containsKey(p.getFileName().toString())) {
                    Files.delete(p);
                }
            }
        }
        for (Map.Entry<String, String> f : out.files().entrySet()) {
            Files.writeString(dir.resolve(f.getKey()), f.getValue(), StandardCharsets.UTF_8);
        }
        Files.writeString(DISPLACED, out.displaced(), StandardCharsets.UTF_8);
    }

