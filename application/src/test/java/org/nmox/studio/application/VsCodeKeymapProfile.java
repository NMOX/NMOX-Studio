    // ---- the cluster, as the system filesystem merges it -----------------

    /** A file of the merged layers: its {@code originalFile} ("method:…" for a methodvalue) and its flags. */
    record LayerFile(String original, boolean nmoxShortcut) {
    }

    record Bind(String key, String action, boolean remove) {
    }

    /** One editor keybinding file as a layer registers it. */
